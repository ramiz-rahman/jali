/**
 * MAC address facts: which vendor made the network chip (from the OUI, the first three bytes), and the two flag
 * bits in the first byte that decide whether an address is a real hardware address at all.
 */
import { OUI_VENDORS } from "./oui-data";
import { normaliseMac } from "./net";

let table: Map<string, string> | undefined;

/** The prefix table, built on first use from the per-vendor strings in oui-data.ts. */
function prefixes(): Map<string, string> {
  if (!table) {
    table = new Map();
    for (const [vendor, run] of Object.entries(OUI_VENDORS)) {
      for (let i = 0; i + 6 <= run.length; i += 6) table.set(run.slice(i, i + 6), vendor);
    }
  }
  return table;
}

/**
 * Vendors that make the Wi-Fi module, not the product: the brand on the box is probably someone else's, so a hit
 * here says "what chip", not "who sold it".
 */
const MODULE_MAKERS = new Set([
  "Espressif",
  "Tuya",
  "AzureWave",
  "Ampak",
  "Liteon",
  "Foxconn",
  "Universal Global Scientific",
  "Bilian (Wi-Fi modules)",
  "Gaoshengda (Wi-Fi modules)",
  "AltoBeam",
  "Bouffalo",
  "Beken",
  "Goertek",
  "Fn-Link",
  "Shenzhen iComm",
  "Luxshare",
  "WNC",
  "Alpsalpine",
  "Cloud Network Technology",
  "Gongjin",
  "Earda",
  "Chuangwei-RGB",
  "Youhua",
  "Tinno",
]);

export interface MacInfo {
  /** Lower-case, colon separated. */
  mac: string;
  /** Locally administered bit (0x02 of the first byte): software chose this address, a vendor did not. */
  randomised: boolean;
  /** Group bit (0x01): the address names a set of receivers, never one device. */
  multicast: boolean;
  broadcast: boolean;
  /** Vendor from the OUI. Undefined for randomised addresses (no vendor assigned them) and for unlisted OUIs. */
  vendor?: string;
  /** The vendor makes the module inside, not the product. */
  moduleMaker: boolean;
}

export function describeMac(text: string): MacInfo | undefined {
  const mac = normaliseMac(text);
  if (!mac) return undefined;
  const first = parseInt(mac.slice(0, 2), 16);
  const randomised = (first & 0x02) !== 0;
  const multicast = (first & 0x01) !== 0;
  const broadcast = mac === "ff:ff:ff:ff:ff:ff";
  const vendor =
    randomised || multicast
      ? undefined
      : prefixes().get(mac.slice(0, 8).replace(/:/g, "").toUpperCase());
  return {
    mac,
    randomised,
    multicast,
    broadcast,
    vendor,
    moduleMaker: vendor !== undefined && MODULE_MAKERS.has(vendor),
  };
}

/** Vendor for a MAC, or undefined. */
export const vendorOf = (mac: string): string | undefined => describeMac(mac)?.vendor;

/** How many vendors and prefixes the table holds, for the on-screen credit. */
export function tableSize(): { vendors: number; prefixes: number } {
  return { vendors: Object.keys(OUI_VENDORS).length, prefixes: prefixes().size };
}

