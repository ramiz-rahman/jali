/**
 * The shapes the capture reader, the dissectors, the analysis and the panes share: a capture is a list of packets,
 * and each packet is a stack of headers, each a tree of fields that knows which bytes it came from.
 */

/** Where a field sits in the stack, for colour: link, internet, transport, application, and what nobody can read. */
export type Layer = "link" | "net" | "transport" | "app" | "crypt";

export const LAYERS: readonly Layer[] = ["link", "net", "transport", "app", "crypt"];

export const LAYER_NAMES: Record<Layer, string> = {
  link: "Link",
  net: "Internet",
  transport: "Transport",
  app: "Application",
  crypt: "Encrypted",
};

/** The protocols the dissectors know, as ids a filter and the panes use. */
export type ProtoId =
  | "frame"
  | "eth"
  | "vlan"
  | "sll"
  | "loop"
  | "arp"
  | "ip"
  | "ipv6"
  | "icmp"
  | "icmpv6"
  | "udp"
  | "tcp"
  | "dns"
  | "dhcp"
  | "http"
  | "tls"
  | "quic"
  | "data";

/**
 * One dissected value. `offset` and `length` are into the packet's captured bytes; a field with length 0 has no
 * bytes of its own on this packet (frame metadata, or a value reassembled from earlier packets).
 */
export interface Field {
  /** Unique within its packet: the tree's value and the highlight's key. */
  id: string;
  name: string;
  /** The value as a person reads it: "64", "0x4000 (Don't fragment)", "www.example.com". */
  value: string;
  offset: number;
  length: number;
  layer: Layer;
  /** One line for an expert: why this field matters, what it gives away, what goes wrong with it. */
  why?: string;
  /** Something is wrong with it: a bad checksum, a header cut short. */
  warn?: boolean;
  children?: Field[];
}

/** One protocol's header in a packet: a field whose children are the header's fields. */
export interface Header extends Field {
  proto: ProtoId;
  /** The short name for columns and chips: "IPv4", "TCP", "TLS". */
  short: string;
  /** Bytes from the header's start to the end of what it carries: header and payload, for the encapsulation. */
  extent: number;
}

/** Wireshark-style TCP analysis, computed per stream in capture order. */
export type AnalysisKind =
  | "retransmission"
  | "fast-retransmission"
  | "dup-ack"
  | "window-update"
  | "zero-window"
  | "lost-segment";

export interface Analysis {
  kind: AnalysisKind;
  /** As Wireshark prints it in the Info column: "TCP Dup ACK 14#1". */
  label: string;
  why: string;
}

/** Addresses and ports, when the packet is IP. */
export interface Flow {
  src: string;
  dst: string;
  transport?: "tcp" | "udp";
  sport?: number;
  dport?: number;
}

export interface Packet {
  /** 1-based, as in Wireshark's No. column. */
  n: number;
  /** Seconds since the Unix epoch. */
  time: number;
  /** Seconds since the capture's first packet. */
  rel: number;
  data: Uint8Array;
  /** The length on the wire; more than `data.length` when the capture's snap length cut the packet. */
  wireLength: number;
  linkType: number;
  iface?: string;
  headers: Header[];
  /** The bytes with QUIC Initial payloads decrypted and header protection removed, when there were any. */
  plain?: Uint8Array;
  src: string;
  dst: string;
  /** The topmost protocol's short name. */
  protocol: string;
  info: string;
  protos: ReadonlySet<ProtoId>;
  flow?: Flow;
  /** The TCP stream or UDP conversation it belongs to, numbered in order of first appearance. */
  stream?: { transport: "tcp" | "udp"; index: number };
  analysis: Analysis[];
}

export interface Capture {
  id: string;
  title: string;
  summary: string;
  /** Generated by the app, not recorded. */
  madeUp: boolean;
  fileName?: string;
  format: "pcap" | "pcapng";
  packets: Packet[];
  /** Stable names for packet numbers, for lessons. */
  marks: Readonly<Record<string, number>>;
  /** Not fatal: what was odd about the file ("the last packet was cut off"). */
  warnings: string[];
}
