const BY_ID = new Map(GLOSSARY.map((g) => [g.id, g]));

export const termById = (id: string): Term | undefined => BY_ID.get(id);

/** The terms whose name or id contains what was typed, in alphabetical order. */
export function filterTerms(query: string): Term[] {
  const q = query.trim().toLowerCase();
  const sorted = [...GLOSSARY].sort((a, b) =>
    a.term.localeCompare(b.term, "en", { sensitivity: "base" }),
  );
  return q ? sorted.filter((t) => t.term.toLowerCase().includes(q) || t.id.includes(q)) : sorted;
}
