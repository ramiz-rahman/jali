const byId = new Map(PLACES.map((p) => [p.id, p]));

export const placeById = (id: string): Place | undefined => byId.get(id);

/** A place we know, or a clear error for a programming mistake. */
export function mustPlace(id: string): Place {
  const p = byId.get(id);
  if (!p) throw new Error(`No place called ${id}`);
  return p;
}

/** Whether a day can hold the place: a sight or a meal (a hotel is where the day starts, an airport its flight). */
export const isPlannable = (p: Place) => p.category === "sight" || p.category === "food";

/** Whether `id` is a sight or a meal in `city`: what a day there may hold. */
export function isPlannableIn(id: string, city: CityId): boolean {
  const p = placeById(id);
  return !!p && isPlannable(p) && p.city === city;
}

