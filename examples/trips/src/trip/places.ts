/**
 * The places of the bundled trip: a week in Thailand, Bangkok first, then Phuket.
 *
 * Sights, beaches and the two airports are real places at their real coordinates. Their opening hours, visit
 * lengths and ticket prices are made up for the example. Every hotel and restaurant is fictional: invented names at
 * invented spots in real neighbourhoods, with invented prices. None of them is a real business. Prices are in US
 * dollars, at levels that are plausible for Thailand.
 */
import type { CityId } from "./cities";

export type Category = "sight" | "food" | "stay" | "airport";

export interface Place {
  id: string;
  name: string;
  category: Category;
  city: CityId;
  /** The neighbourhood, for lists. */
  area: string;
  lat: number;
  lng: number;
  /** Opening hours as people read them; for a hotel, when check-in opens ("From 14:00"). */
  hours: string;
  /** A typical visit, in minutes. */
  visitMin: number;
  /** In US dollars: a ticket, a typical meal for one, or a night for a hotel. 0 is free. */
  price: number;
  notes: string;
  /** A made-up business (every hotel and restaurant here). */
  fictional: boolean;
  /** A few words of what it is ("Temple", "Beach"). */
  kind: string;
  /** On the Thonburi bank of the Chao Phraya, across the river from old Bangkok: the way there is a ferry. */
  acrossRiver?: boolean;
}

/** What each entry below gives: everything its category doesn't already say. */
type Entry = Omit<Place, "category" | "fictional">;

/** A real sight or beach. */
const sight = (p: Entry): Place => ({ ...p, category: "sight", fictional: false });

/** A made-up restaurant: a meal takes an hour unless it says otherwise. */
const food = (p: Omit<Entry, "visitMin"> & { visitMin?: number }): Place => ({
  visitMin: 60,
  ...p,
  category: "food",
  fictional: true,
});

/** A made-up hotel: its price is a night, and staying there takes no time from the day. */
const stay = (p: Omit<Entry, "visitMin">): Place => ({
  ...p,
  visitMin: 0,
  category: "stay",
  fictional: true,
});

/** One of the two real airports. */
const airport = (p: Pick<Entry, "city" | "id" | "name" | "lat" | "lng" | "notes">): Place => ({
  ...p,
  area: "Airport",
  kind: "Airport",
  visitMin: 0,
  price: 0,
  hours: "Open all day",
  category: "airport",
  fictional: false,
});

